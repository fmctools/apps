#!/usr/bin/env python3
"""Generates src/font.rs: packed 4-bit-per-pixel (16-level AA) fonts from Barlow SemiBold (SIL OFL 1.1)."""
import os
from pathlib import Path
import sys
from PIL import Image, ImageDraw, ImageFont

DEFAULT_FONT = Path(__file__).with_name("Barlow-SemiBold.ttf")

CHARS_UI = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.:!+-/<>#%"
CHARS_LG = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!"

SPECS = [
    ("FONT_SM", 16, CHARS_UI, False),
    ("FONT_MD", 22, CHARS_UI, True),
    ("FONT_LG", 44, CHARS_LG, True),
]


def render_font(font_path: Path, name: str, size: int, chars: str, tabular_digits: bool):
    f = ImageFont.truetype(str(font_path), size)

    raw_glyphs = {}
    max_digit_adv = 0
    min_top = 999

    for ch in chars:
        adv = max(1, int(round(f.getlength(ch))))
        if ch.isdigit():
            max_digit_adv = max(max_digit_adv, adv)
        if ch == " ":
            raw_glyphs[ch] = (0, 0, 0, 0, adv, [])
            continue
        cw, ch_h = size * 2 + 16, size * 2 + 16
        ox, oy = 8, 8
        img = Image.new("L", (cw, ch_h), 0)
        d = ImageDraw.Draw(img)
        d.text((ox, oy), ch, font=f, fill=255)
        bbox = img.getbbox()
        if not bbox:
            raw_glyphs[ch] = (0, 0, 0, 0, adv, [])
            continue
        x0, y0, x1, y1 = bbox
        min_top = min(min_top, y0 - oy)
        w, h = x1 - x0, y1 - y0
        px = img.crop(bbox).tobytes()
        raw_glyphs[ch] = (x0 - ox, y0 - oy, w, h, adv, px)

    glyph_entries = []
    blob = bytearray()

    for ch in chars:
        xo, yo, w, h, adv, px = raw_glyphs[ch]
        if tabular_digits and ch.isdigit():
            dx = (max_digit_adv - adv) // 2
            xo += dx
            adv = max_digit_adv
        yo_norm = yo - min_top if w > 0 else 0
        offset = len(blob)
        # Pack 2 pixels per byte (4 bits per pixel = 16 coverage levels, high nibble first).
        i = 0
        n = len(px)
        while i < n:
            hi = (px[i] * 15 + 127) // 255
            lo = (px[i + 1] * 15 + 127) // 255 if i + 1 < n else 0
            blob.append((hi << 4) | lo)
            i += 2
        glyph_entries.append((ch, xo, yo_norm, w, h, adv, offset))

    return {
        "name": name,
        "chars": chars,
        "entries": glyph_entries,
        "blob": bytes(blob),
    }


def main():
    font_path = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("BARLOW_FONT", DEFAULT_FONT))
    if not font_path.is_file():
        raise SystemExit(f"Font not found: {font_path} (pass path to Barlow-SemiBold.ttf, SIL OFL 1.1)")
    fonts = [render_font(font_path, *s) for s in SPECS]
    out_path = Path(__file__).resolve().parent.parent / "src" / "font.rs"
    lines = [
        "//! Smooth 4-bpp (16-level) anti-aliased fonts generated by `tools/gen_font.py`.",
        "//!",
        "//! Glyphs rasterized from Barlow SemiBold (Copyright 2017 The Barlow Project Authors,",
        "//! https://github.com/jpt/barlow), licensed under the SIL Open Font License 1.1",
        "//! (https://scripts.sil.org/OFL).",
        "",
        "use cmf_wp2_ui::draw::Run;",
        "use cmf_wp2_ui::{ONE, Rgb, Surface};",
        "",
        "#[derive(Clone, Copy)]",
        "pub struct Glyph {",
        "    pub ch: u8,",
        "    pub x_off: i8,",
        "    pub y_off: i8,",
        "    pub w: u8,",
        "    pub h: u8,",
        "    pub adv: u8,",
        "    pub offset: u16,",
        "}",
        "",
        "pub struct Font {",
        "    pub glyphs: &'static [Glyph],",
        "    pub data: &'static [u8],",
        "}",
        "",
        "impl Font {",
        "    fn glyph(&self, b: u8) -> Option<&Glyph> {",
        "        self.glyphs.iter().find(|g| g.ch == b)",
        "    }",
        "",
        "    pub fn width(&self, text: &str) -> i32 {",
        "        let mut w = 0i32;",
        "        for b in text.bytes() {",
        "            w += self.glyph(b).map_or(0, |g| g.adv as i32);",
        "        }",
        "        w",
        "    }",
        "",
        "    pub fn draw(&self, s: &mut impl Surface, x: i32, y: i32, text: &str, fg: Rgb, bg: Rgb) {",
        "        let mut pal = [0u16; 16];",
        "        pal[0] = bg.rgb565();",
        "        pal[15] = fg.rgb565();",
        "        for i in 1..15 {",
        "            pal[i] = bg.mix(fg, (i as i32) * ONE / 15).rgb565();",
        "        }",
        "        let mut cx = x;",
        "        for b in text.bytes() {",
        "            let Some(g) = self.glyph(b) else { continue };",
        "            let gw = g.w as usize;",
        "            let gh = g.h as usize;",
        "            if gw > 0 && gh > 0 {",
        "                let gx = cx + g.x_off as i32;",
        "                let gy = y + g.y_off as i32;",
        "                let start = g.offset as usize;",
        "                for row in 0..gh {",
        "                    let mut run = Run::new(s, gy + row as i32, false);",
        "                    for col in 0..gw {",
        "                        let idx = row * gw + col;",
        "                        let byte = self.data[start + (idx >> 1)];",
        "                        let lvl = if (idx & 1) == 0 { byte >> 4 } else { byte & 0x0F } as usize;",
        "                        if lvl != 0 {",
        "                            run.put(gx + col as i32, 1, pal[lvl]);",
        "                        }",
        "                    }",
        "                }",
        "            }",
        "            cx += g.adv as i32;",
        "        }",
        "    }",
        "",
        "    pub fn centre(&self, s: &mut impl Surface, cx: i32, y: i32, text: &str, fg: Rgb, bg: Rgb) {",
        "        let w = self.width(text);",
        "        self.draw(s, cx - w / 2, y, text, fg, bg);",
        "    }",
        "}",
        "",
    ]

    total_bytes = 0
    for f in fonts:
        name = f["name"]
        data_name = f"{name}_DATA"
        glyphs_name = f"{name}_GLYPHS"
        total_bytes += len(f["blob"])
        lines.append(f"static {data_name}: [u8; {len(f['blob'])}] = [")
        for i in range(0, len(f["blob"]), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in f["blob"][i:i + 16])
            lines.append(f"    {chunk},")
        lines.append("];\n")
        lines.append(f"static {glyphs_name}: [Glyph; {len(f['entries'])}] = [")
        for ch, xo, yo, w, h, adv, off in f["entries"]:
            lines.append(
                f"    Glyph {{ ch: {ord(ch)}, x_off: {xo}, y_off: {yo}, w: {w}, h: {h}, adv: {adv}, offset: {off} }},"
            )
        lines.append("];\n")
        lines.append(
            f"pub static {name}: Font = Font {{ glyphs: &{glyphs_name}, data: &{data_name} }};\n"
        )

    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} (total font data: {total_bytes} bytes)")


if __name__ == "__main__":
    main()
