#![allow(non_upper_case_globals)]

//! NType 82 Regular glyph subset used by this Nothing-related CMF watch app.
//!
//! The uploaded OTF is not redistributed. This module contains only the small pre-rendered
//! glyph subset needed by the interface, with the original proportions preserved.

use cmf_wp2_ui::Surface;

pub(crate) struct Glyph {
    pub code: u8,
    pub width: u8,
    pub rows: &'static [u32],
}

#[derive(Clone, Copy)]
pub(crate) enum FontSize {
    Small,
    Large,
}

impl FontSize {
    fn glyphs(self) -> &'static [Glyph] {
        match self {
            FontSize::Small => &SMALL_GLYPHS,
            FontSize::Large => &LARGE_GLYPHS,
        }
    }

    fn height(self) -> usize {
        match self {
            FontSize::Small => SMALL_HEIGHT,
            FontSize::Large => LARGE_HEIGHT,
        }
    }
}

fn glyph(font: FontSize, ch: char) -> &'static Glyph {
    let code = ch as u8;
    font.glyphs()
        .iter()
        .find(|glyph| glyph.code == code)
        .or_else(|| font.glyphs().iter().find(|glyph| glyph.code == b'?'))
        .expect("question glyph")
}

fn char_width(font: FontSize, ch: char) -> i32 {
    glyph(font, ch).width as i32
}

/// Width in screen pixels, including one pixel of tracking between glyphs.
pub(crate) fn width(font: FontSize, text: &str) -> i32 {
    let count = text.chars().count();
    if count == 0 {
        return 0;
    }
    let ink: i32 = text.chars().map(|ch| char_width(font, ch)).sum();
    ink + count as i32 - 1
}

/// Draws text from the left edge and returns its width.
pub(crate) fn draw(
    s: &mut impl Surface,
    x: i32,
    y: i32,
    text: &str,
    colour: u16,
    font: FontSize,
) -> i32 {
    let mut pen = x;
    for ch in text.chars() {
        let glyph = glyph(font, ch);
        for (row, bits) in glyph.rows.iter().enumerate() {
            let mut bit = 0;
            while bit < glyph.width as usize {
                if (*bits & (1 << bit)) == 0 {
                    bit += 1;
                    continue;
                }
                let start = bit;
                while bit < glyph.width as usize && (*bits & (1 << bit)) != 0 {
                    bit += 1;
                }
                s.rect(
                    pen + start as i32,
                    y + row as i32,
                    (bit - start) as i32,
                    1,
                    colour,
                );
            }
        }
        pen += glyph.width as i32 + 1;
    }
    width(font, text)
}

/// Draws text centred on the round panel.
pub(crate) fn centre(
    s: &mut impl Surface,
    centre_x: i32,
    y: i32,
    text: &str,
    colour: u16,
    font: FontSize,
) -> i32 {
    let x = centre_x - width(font, text) / 2;
    draw(s, x, y, text, colour, font)
}

fn clipped_parts(font: FontSize, text: &str, max_width: i32) -> (usize, i32, bool) {
    let full_width = width(font, text);
    if full_width <= max_width {
        return (text.len(), full_width, false);
    }

    let ellipsis_width = width(font, "...");
    let mut prefix_ink = 0;
    let mut prefix_count = 0;
    let mut prefix_len = 0;
    for (index, ch) in text.char_indices() {
        let next_ink = prefix_ink + char_width(font, ch);
        let next_count = prefix_count + 1;
        let next_width = next_ink + next_count - 1;
        if next_width + ellipsis_width > max_width {
            break;
        }
        prefix_ink = next_ink;
        prefix_count = next_count;
        prefix_len = index + ch.len_utf8();
    }
    let prefix_width = prefix_ink + prefix_count.saturating_sub(1);
    (prefix_len, prefix_width + ellipsis_width, true)
}

/// Draws text from the left edge, truncating it with an ellipsis when it exceeds `max_width`.
pub(crate) fn draw_clipped(
    s: &mut impl Surface,
    x: i32,
    y: i32,
    text: &str,
    max_width: i32,
    colour: u16,
    font: FontSize,
) -> i32 {
    let (prefix_len, clipped_width, truncated) = clipped_parts(font, text, max_width);
    if !truncated {
        return draw(s, x, y, text, colour, font);
    }

    let prefix = &text[..prefix_len];
    let prefix_width = width(font, prefix);
    draw(s, x, y, prefix, colour, font);
    draw(s, x + prefix_width, y, "...", colour, font);
    clipped_width
}

/// Draws clipped text centred on the round panel.
pub(crate) fn centre_clipped(
    s: &mut impl Surface,
    centre_x: i32,
    y: i32,
    text: &str,
    max_width: i32,
    colour: u16,
    font: FontSize,
) -> i32 {
    let (_, clipped_width, _) = clipped_parts(font, text, max_width);
    let x = centre_x - clipped_width / 2;
    draw_clipped(s, x, y, text, max_width, colour, font)
}

